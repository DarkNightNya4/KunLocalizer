function I:Language()
    local preferred=K.Startup and K.Startup:UILanguage() or 'auto'
    if self.supported[preferred] then return preferred end
    local locale=GetLocale()
    return (locale=='zhCN' or locale=='zhTW') and 'zhCN' or 'enUS'
end
function I:Text(key)
    -- 未完成语言不展示成已支持；缺少单条文案时回退英文，不发起网络翻译。
    local language=self:Language()
    return (words[language] and words[language][key]) or words.enUS[key] or key
end
